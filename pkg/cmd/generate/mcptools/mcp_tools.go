const (
	toolsFileName = "tools.json"
	header        = "{/* Generated by docli generate mcp-tools from tools.json. Don't edit. */}"
)

// section is a part of the catalog table: the group a tool belongs to and the
// label shown in the table.
type section struct {
	group string
	label string
}

// sections lists the sections of the catalog table, in page order.
var sections = []section{
	{"search", "Search"},
	{"index", "Index configuration"},
	{"recommend", "Recommend"},
	{"analytics", "Analytics"},
	{"agent-studio", "Agent Studio"},
	{"application", "Applications and account"},
}

// directOrder lists the direct tools in the order a client uses them.
// Any other direct tool follows.
var directOrder = []string{
	"algolia_discover_tools",
	"algolia_describe_tool",
	"algolia_call_read_tool",
	"algolia_call_write_tool",
}

var frontmatterTitle = regexp.MustCompile(`(?m)^title:\s*(.+)$`)

// Options represents the options and flags for this command.
type Options struct {
	OutputDir string
	ToolsFile string
	DocsDir   string
}

// Tool is an MCP tool as written to tools.json by algolia/mcp-server.
type Tool struct {
	Name        string   `json:"name"`
	Group       string   `json:"group"`
	Effect      string   `json:"effect"`
	Description string   `json:"description"`
	Endpoints   []string `json:"endpoints"`
}

// Tools groups the tools by the table they're listed in.
type Tools struct {
	Direct  []Tool `json:"direct"`
	Catalog []Tool `json:"catalog"`
	ChatGPT []Tool `json:"chatgpt"`
}

// row is a line of a rendered table.
type row struct {
	tool        string
	description string
}

// NewCommand returns a new instance of the `generate mcp-tools` command.
func NewCommand() *cobra.Command {
	opts := &Options{}

	cmd := &cobra.Command{
		Use:   "mcp-tools",
		Short: "Generate the tool tables of the Productivity MCP guide",
		Long: heredoc.Doc(`
			This command renders the tools of the Productivity MCP
			as three Markdown tables, one MDX snippet each:
			direct.mdx, catalog.mdx, and chatgpt.mdx.

			The tools come from a tools.json file written by algolia/mcp-server.
			A tool is described by its description or,
			without one, by a link to the API reference page of its only endpoint,
			titled like that page.

			The command fails instead of rendering a table
			that the wording of the guide would contradict:
			a tool that changes data, an empty table, a group without a section,
			or a tool it can't describe.
		`),
		Example: heredoc.Doc(`
			# Run from the root of algolia/docs-new
			docli gen mcp-tools -o snippets/mcp/productivity-tools
		`),
		RunE: func(cmd *cobra.Command, _ []string) error {
			printer, err := output.New(cmd)
			if err != nil {
				return err
			}

			return runCommand(opts, printer)
		},
	}

	cmd.Flags().
		StringVarP(&opts.OutputDir, "output", "o", ".", "Output directory for the generated snippet files")
	cmd.Flags().
		StringVar(&opts.ToolsFile, "tools-file", "", "Path to the tools.json file (default: tools.json in output dir)")
	cmd.Flags().
		StringVar(&opts.DocsDir, "docs-dir", ".", "Root of the docs repository, to look up API reference pages")

	return cmd
}

func runCommand(opts *Options, printer *output.Printer) error {
	if opts.ToolsFile == "" {
		opts.ToolsFile = filepath.Join(opts.OutputDir, toolsFileName)
	}

	if err := validate.ExistingFile(opts.ToolsFile, "tools file"); err != nil {
		return err
	}

	if err := validate.ExistingDir(opts.DocsDir, "docs directory"); err != nil {
		return err
	}

	if err := validate.OutputDir(opts.OutputDir, "output directory"); err != nil {
		return err
	}

	tools, err := readTools(opts.ToolsFile)
	if err != nil {
		return err
	}

	snippets, err := renderSnippets(tools, opts.DocsDir)
	if err != nil {
		return err
	}

	return writeSnippets(opts.OutputDir, snippets, printer)
}

func readTools(path string) (*Tools, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read tools file %s: %w", path, err)
	}

	var file struct {
		Tools Tools `json:"tools"`
	}

	if err = json.Unmarshal(data, &file); err != nil {
		return nil, fmt.Errorf("parse tools file %s: %w", path, err)
	}

	return &file.Tools, nil
}

// renderSnippets renders the three tables, keyed by file name. It returns an
// error listing every problem that makes a table contradict the guide.
func renderSnippets(tools *Tools, docsDir string) (map[string]string, error) {
	problems := validateTools(tools)

	described := map[string]string{}

	for _, tool := range tools.all() {
		description, problem := describe(tool, docsDir)
		if problem != "" {
			problems = append(problems, problem)
		}

		described[tool.Name] = description
	}

	if len(problems) > 0 {
		return nil, fmt.Errorf(
			"can't render the Productivity MCP tool tables:\n  - %s",
			strings.Join(problems, "\n  - "),
		)
	}

	direct := append([]Tool(nil), tools.Direct...)
	sort.SliceStable(direct, func(i, j int) bool {
		return directRank(direct[i]) < directRank(direct[j])
	})

	return map[string]string{
		"direct.mdx":  renderTable(toRows(direct, described)),
		"catalog.mdx": renderTable(catalogRows(tools.Catalog, described)),
		"chatgpt.mdx": renderTable(toRows(tools.ChatGPT, described)),
	}, nil
}

func toRows(tools []Tool, described map[string]string) []row {
	rows := make([]row, 0, len(tools))
	for _, tool := range tools {
		rows = append(rows, row{tool: "`" + tool.Name + "`", description: described[tool.Name]})
	}

	return rows
}

// catalogRows groups the catalog tools by section, each led by a label row.
func catalogRows(catalog []Tool, described map[string]string) []row {
	var rows []row

	for _, s := range sections {
		var inSection []Tool

		for _, tool := range catalog {
			if tool.Group == s.group {
				inSection = append(inSection, tool)
			}
		}

		if len(inSection) > 0 {
			rows = append(rows, row{tool: "**" + s.label + "**"})
			rows = append(rows, toRows(inSection, described)...)
		}
	}

	return rows
}

func (t *Tools) all() []Tool {
	all := make([]Tool, 0, len(t.Direct)+len(t.Catalog)+len(t.ChatGPT))
	all = append(all, t.Direct...)
	all = append(all, t.Catalog...)
	all = append(all, t.ChatGPT...)

	return all
}

func directRank(tool Tool) int {
	for i, name := range directOrder {
		if name == tool.Name {
			return i
		}
	}

	return len(directOrder)
}

// validateTools returns the reasons the guide's wording wouldn't match the tools.
func validateTools(tools *Tools) []string {
	var problems []string

	for _, tool := range tools.all() {
		if tool.Effect != "read" {
			problems = append(problems, fmt.Sprintf(
				"%s changes data, but the guide says Productivity MCP is read-only: "+
					"update that wording and add a table for write tools first",
				tool.Name,
			))
		}
	}

	for _, table := range []struct {
		tools []Tool
		label string
	}{
		{tools.Direct, "direct-tools"},
		{tools.Catalog, "algolia_call_read_tool"},
		{tools.ChatGPT, "ChatGPT"},
	} {
		if len(table.tools) == 0 {
			problems = append(problems, fmt.Sprintf(
				"No tool for the %s table, which the guide introduces", table.label,
			))
		}
	}

	for _, tool := range tools.Catalog {
		if !hasSection(tool.Group) {
			problems = append(problems, fmt.Sprintf(
				"%s is in group %q, which has no section: add it to the sections of the mcp-tools command",
				tool.Name,
				tool.Group,
			))
		}
	}

	return problems
}

func hasSection(group string) bool {
	for _, s := range sections {
		if s.group == group {
			return true
		}
	}

	return false
}

// describe returns the tool's own description, or a link to the API reference
// page of its only endpoint. It returns a problem when it has neither: the fix
// is in algolia/mcp-server.
func describe(tool Tool, docsDir string) (description, problem string) {
	if tool.Description != "" {
		return tool.Description, ""
	}

	if len(tool.Endpoints) != 1 {
		what := "several endpoints"
		if len(tool.Endpoints) == 0 {
			what = "no endpoint"
		}

		return "", fmt.Sprintf(
			"%s has %s: give it a docsDescription in algolia/mcp-server", tool.Name, what,
		)
	}

	api, operationID, _ := strings.Cut(tool.Endpoints[0], "/")
	href := fmt.Sprintf("/doc/rest-api/%s/%s", api, utils.ToKebabCase(operationID))

	title := pageTitle(filepath.Join(docsDir, filepath.FromSlash(href)+".mdx"))
	if title == "" {
		return "", fmt.Sprintf(
			"%s: %s doesn't exist, so give it a docsDescription in algolia/mcp-server",
			tool.Name, href,
		)
	}

	return fmt.Sprintf("[%s](%s)", title, href), ""
}

// pageTitle returns the title in the frontmatter of an MDX page,
// or an empty string if the page or its title is missing.
func pageTitle(path string) string {
	data, err := os.ReadFile(path)
	if err != nil {
		return ""
	}

	text := strings.ReplaceAll(string(data), "\r\n", "\n")
	if !strings.HasPrefix(text, "---\n") {
		return ""
	}

	frontmatter, _, found := strings.Cut(text[len("---\n"):], "\n---")
	if !found {
		return ""
	}

	match := frontmatterTitle.FindStringSubmatch(frontmatter)
	if match == nil {
		return ""
	}

	title := strings.TrimSpace(match[1])
	if len(title) >= 2 && (title[0] == '"' || title[0] == '\'') && title[len(title)-1] == title[0] {
		title = title[1 : len(title)-1]
	}

	return title
}

// renderTable renders a Markdown table with columns padded the way Prettier
// formats them, so a diff shows only the rows that changed. A cell is one line,
// and a bare pipe would end it.
func renderTable(rows []row) string {
	cells := make([]row, 0, len(rows)+1)
	cells = append(cells, row{tool: "Tool", description: "Description"})

	for _, r := range rows {
		cells = append(cells, row{
			tool: r.tool,
			description: strings.ReplaceAll(
				strings.Join(strings.Fields(r.description), " "),
				"|",
				`\|`,
			),
		})
	}

	var toolWidth, descriptionWidth int

	for _, c := range cells {
		toolWidth = max(toolWidth, utf8.RuneCountInString(c.tool))
		descriptionWidth = max(descriptionWidth, utf8.RuneCountInString(c.description))
	}

	var sb strings.Builder

	sb.WriteString(header + "\n\n")

	line := func(tool, description string) {
		fmt.Fprintf(&sb, "| %s | %s |\n", pad(tool, toolWidth), pad(description, descriptionWidth))
	}

	line(cells[0].tool, cells[0].description)
	line(strings.Repeat("-", toolWidth), strings.Repeat("-", descriptionWidth))

	for _, c := range cells[1:] {
		line(c.tool, c.description)
	}

	return sb.String()
}

func pad(s string, width int) string {
	return s + strings.Repeat(" ", max(0, width-utf8.RuneCountInString(s)))
}

// sortedNames returns the file names of the snippets, in alphabetical order.
func sortedNames(snippets map[string]string) []string {
	names := make([]string, 0, len(snippets))
	for name := range snippets {
		names = append(names, name)
	}

	sort.Strings(names)

	return names
}

// staleSnippets returns the paths of the snippets that differ from the files on disk.
func staleSnippets(outputDir string, snippets map[string]string) ([]string, error) {
	var stale []string

	for _, name := range sortedNames(snippets) {
		path := filepath.Join(outputDir, name)

		current, err := os.ReadFile(path)
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return nil, fmt.Errorf("read %s: %w", path, err)
		}

		if err != nil || !bytes.Equal(current, []byte(snippets[name])) {
			stale = append(stale, path)
		}
	}

	return stale, nil
}

func writeSnippets(outputDir string, snippets map[string]string, printer *output.Printer) error {
	stale, err := staleSnippets(outputDir, snippets)
	if err != nil {
		return err
	}

	if len(stale) == 0 {
		printer.Infof("Productivity MCP tool tables are up to date\n")

		return nil
	}

	if !printer.IsDryRun() {
		if err = os.MkdirAll(outputDir, 0o700); err != nil {
			return fmt.Errorf("create output directory %s: %w", outputDir, err)
		}
	}

	for _, path := range stale {
		content := snippets[filepath.Base(path)]

		if err = printer.WriteFile(path, func(w io.Writer) error {
			_, werr := io.WriteString(w, content)

			return werr
		}); err != nil {
			return err
		}

		printer.Infof("Wrote %s\n", path)
	}

	return nil
}
